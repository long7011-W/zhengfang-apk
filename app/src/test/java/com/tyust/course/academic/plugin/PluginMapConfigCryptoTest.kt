package com.tyust.course.academic.plugin

import android.app.Application
import android.util.Base64
import org.json.JSONObject
import org.junit.Assert.*
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import java.io.IOException
import java.security.KeyFactory
import java.security.KeyPair
import java.security.spec.PKCS8EncodedKeySpec
import java.security.spec.X509EncodedKeySpec

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [28], manifest = Config.NONE, application = Application::class)
class PluginMapConfigCryptoTest {
    private fun fixture() = JSONObject(javaClass.getResourceAsStream("/map-client-config-v1.json")!!.bufferedReader().use { it.readText() })
    private fun bytes(value: String) = Base64.decode(value, Base64.URL_SAFE or Base64.NO_WRAP or Base64.NO_PADDING)
    private fun exchange(fixture: JSONObject): PluginMapConfigCrypto.Exchange {
        val request = fixture.getJSONObject("request")
        val factory = KeyFactory.getInstance("EC")
        val pair = KeyPair(factory.generatePublic(X509EncodedKeySpec(bytes(request.getString("clientPublicKey")))),
            factory.generatePrivate(PKCS8EncodedKeySpec(bytes(fixture.getString("clientPrivateKey")))))
        return PluginMapConfigCrypto.create(fixture.getString("credential"), request.getString("packageName"), request.getInt("appVersionCode"),
            request.getString("certSha256"), request.getLong("timestamp"), request.getString("nonce"), pair)
    }

    @Test fun nativeRequestAndDecryptionMatchTheActualWorkerCryptoImplementation() {
        // Generated by maps-client-config.test.mjs in the real Workers runtime,
        // independently decrypted by Node's OpenSSL APIs before being saved.
        val fixture = fixture()
        val exchange = exchange(fixture)
        assertEquals(fixture.getJSONObject("request").getString("signature"), exchange.body.getString("signature"))
        val configuration = exchange.open(fixture.getJSONObject("response"), fixture.getJSONObject("request").getLong("timestamp"))
        assertEquals(fixture.getJSONObject("payload").getString("apiKey"), configuration.apiKey)
        assertEquals(fixture.getJSONObject("payload").getLong("expiresAt"), configuration.expiresAt)
        assertFalse(configuration.toString().contains(configuration.apiKey!!))
    }

    @Test fun modifiedEnvelopeFieldsAreRejectedBeforeReturningAnyKey() {
        val fixture = fixture()
        val exchange = exchange(fixture)
        val now = fixture.getJSONObject("request").getLong("timestamp")
        for (field in listOf("ciphertext", "iv", "serverPublicKey", "nonce", "proof")) {
            val response = JSONObject(fixture.getJSONObject("response").toString())
            val value = response.getString(field)
            response.put(field, (if (value.first() == 'a') "b" else "a") + value.drop(1))
            val error = assertThrows(IOException::class.java) { exchange.open(response, now) }
            assertEquals("地图配置校验失败，请重试", error.message)
        }
        val alteredExpiry = JSONObject(fixture.getJSONObject("response").toString()).put("expiresAt", now + 10)
        assertThrows(IOException::class.java) { exchange.open(alteredExpiry, now) }
    }

    @Test fun expiredCapturedResponsesAndResponsesForAnotherRequestCannotBeReused() {
        val fixture = fixture()
        val request = fixture.getJSONObject("request")
        val response = fixture.getJSONObject("response")
        assertThrows(IOException::class.java) { exchange(fixture).open(response, response.getLong("expiresAt") + 1) }
        val other = PluginMapConfigCrypto.create(fixture.getString("credential"), "com.tyust.course", 120, request.getString("certSha256"), request.getLong("timestamp"))
        assertThrows(IOException::class.java) { other.open(response, request.getLong("timestamp")) }
    }
}
